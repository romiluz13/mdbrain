export function isScreenedName(name: string): boolean {
	const lower = name.toLowerCase()
	const words = new Set(lower.split(/[^a-z0-9]+/).filter(Boolean))
	return !WELL_KNOWN_COMPANY_WORDS.some((blocked) =>
		blocked.includes(" ") ? lower.includes(blocked) : words.has(blocked),
	)
}

// Rendered text uses ordinary words, so only distinctive brand words are
// matched case-insensitively; short acronyms match only in capitals.
const COMMON_ENGLISH = new Set([
	"target",
	"prime",
	"swift",
	"knight",
	"motive",
	"hunt",
	"apple",
])
const ACRONYMS = new Set([
	"dhl",
	"ups",
	"dsv",
	"msc",
	"cma",
	"sap",
	"xpo",
	"man",
])

export function realCompaniesIn(text: string): string[] {
	const found = new Set<string>()
	const lower = text.toLowerCase()
	const words = new Set(lower.split(/[^a-z0-9]+/))
	const upperWords = new Set(
		text.split(/[^A-Za-z0-9]+/).filter((w) => w === w.toUpperCase()),
	)
	for (const brand of WELL_KNOWN_COMPANY_WORDS) {
		if (COMMON_ENGLISH.has(brand)) continue
		if (
			ACRONYMS.has(brand)
				? upperWords.has(brand.toUpperCase())
				: brand.includes(" ")
					? lower.includes(brand)
					: words.has(brand)
		)
			found.add(brand)
	}
	return [...found]
}
